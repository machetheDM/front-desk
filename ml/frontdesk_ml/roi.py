"""ROI sheet for a pilot: measured volumes, stated assumptions, a range, never one number.

    python -m frontdesk_ml.roi docs/engagement/roi-inputs.demo.yaml   (writes docs/engagement/roi-demo.md)

Two kinds of benefit, kept apart because they deserve different trust:

- **Staff time** (measured volume x stated minutes x stated cost): the volume of questions the
  assistant answered comes from the replay, with a Wilson 95% interval on the answered share.
- **Sales from after-hours replies** (stated assumptions only): after-hours buying questions
  answered at once x lead-to-sale rate x the share that would otherwise have gone elsewhere x
  margin. This is the number most likely to be wrong, so the "low" case assumes zero.

Every assumption must name its source; the tool refuses inputs that do not.
"""

from __future__ import annotations

import json
import pathlib
import sys

import yaml

from frontdesk.stats import wilson

ROOT = pathlib.Path(__file__).resolve().parents[2]
CASES = ("low", "mid", "high")


def load(path: pathlib.Path) -> dict:
    cfg = yaml.safe_load(path.read_text(encoding="utf-8"))
    missing = [k for k, v in cfg["assumptions"].items() if not str(v.get("source", "")).strip()]
    if missing or not cfg["monthly_service_cost_zar"].get("source"):
        raise ValueError(f"every assumption needs a source: {missing or ['monthly_service_cost_zar']}")
    return cfg


def compute(cfg: dict, replay_rows: list[dict]) -> dict:
    a = cfg["assumptions"]
    scale = 30 / cfg.get("replay_days", 30)
    n = len(replay_rows)
    answered = sum(r["action"] == "answer" for r in replay_rows)
    _, lo, hi = wilson(answered, n)
    answered_month = {"low": lo * n * scale, "mid": answered * scale, "high": hi * n * scale}
    sales = set(a["sales_intents"]["value"])
    leads = [r for r in replay_rows if r["after_hours"] and r["action"] == "answer" and r["intent"] in sales]
    leads_month = len(leads) * scale
    out = {"questions_per_month": round(n * scale), "answered_per_month": {k: round(v) for k, v in answered_month.items()},
           "after_hours_buying_questions_answered_per_month": round(leads_month), "cases": {}}
    cost = cfg["monthly_service_cost_zar"]["value"]
    for c in CASES:
        hours = answered_month[c] * a["staff_minutes_per_routine_answer"][c] / 60
        time_value = hours * a["staff_cost_per_hour_zar"][c]
        extra_sales = leads_month * a["lead_to_sale_rate"][c] * a["extra_sales_from_instant_after_hours_reply"][c]
        sales_value = extra_sales * a["gross_margin_per_sale_zar"][c]
        benefit = time_value + sales_value
        out["cases"][c] = {"staff_hours_saved": round(hours, 1), "staff_time_value_zar": round(time_value),
                           "extra_sales": round(extra_sales, 2), "extra_margin_zar": round(sales_value),
                           "benefit_zar": round(benefit), "cost_zar": cost, "net_zar": round(benefit - cost),
                           "benefit_per_rand": round(benefit / cost, 2) if cost else None}
    return out


def sheet(cfg: dict, r: dict) -> str:
    a = cfg["assumptions"]
    rows = [("Staff hours saved a month", "staff_hours_saved", ""), ("Value of that time", "staff_time_value_zar", "R"),
            ("Extra sales a month from after-hours replies", "extra_sales", ""), ("Extra gross margin", "extra_margin_zar", "R"),
            ("Total benefit a month", "benefit_zar", "R"), ("Cost a month", "cost_zar", "R"), ("Net a month", "net_zar", "R"),
            ("Benefit per rand spent", "benefit_per_rand", "")]
    def fmt(v, unit):
        if not unit:
            return f"{v}"
        return ("-" if v < 0 else "") + f"{unit}{abs(v):,}".replace(",", " ")
    lines = [f"# ROI sheet: {cfg['tenant']}", "",
             "Generated by `python -m frontdesk_ml.roi`. Volumes are measured from the replay; money is the owner's",
             "stated assumptions, each with its source below. Show the range, never one number.", "",
             f"- Questions a month: {r['questions_per_month']}; answered by the assistant: {r['answered_per_month']['mid']} "
             f"(95% range {r['answered_per_month']['low']} to {r['answered_per_month']['high']})",
             f"- Buying questions answered at once after hours: {r['after_hours_buying_questions_answered_per_month']} a month", "",
             "| | Low | Mid | High |", "|---|---|---|---|"]
    for label, key, unit in rows:
        lines.append(f"| {label} | " + " | ".join(fmt(r["cases"][c][key], unit) for c in CASES) + " |")
    low, mid = r["cases"]["low"], r["cases"]["mid"]
    if low["net_zar"] < 0:
        verdict = (f"**The low case does not pay**: staff time alone is worth {fmt(low['staff_time_value_zar'], 'R')} a month against "
                   f"{fmt(low['cost_zar'], 'R')}. The case rests on after-hours sales, so the pilot must measure them.")
    else:
        verdict = f"**Even the low case pays**: {fmt(low['net_zar'], 'R')} a month net, before any extra sales are counted."
    lines += ["", verdict, f"The mid case returns {mid['benefit_per_rand']} rand for every rand spent.",
              "", "## Assumptions and where they came from", "", "| Assumption | Low | Mid | High | Source |", "|---|---|---|---|---|"]
    for k, v in a.items():
        if "value" in v:
            lines.append(f"| {k.replace('_', ' ')} | {v['value']} | | | {v['source']} |")
        else:
            lines.append(f"| {k.replace('_', ' ')} | {v['low']} | {v['mid']} | {v['high']} | {v['source']} |")
    lines += [f"| monthly service cost (R) | {cfg['monthly_service_cost_zar']['value']} | | | {cfg['monthly_service_cost_zar']['source']} |", "",
              "## How to read it", "",
              "- The staff-time line rests on a measured volume; the sales line rests on assumptions, and the low case",
              "  assumes no extra sales at all. If the low case does not pay, say so to the owner.",
              "- After the pilot, replace the sales assumption with the owner's own records for the 30 days",
              "  (quotes and sales from WhatsApp leads) against the same 30 days before the pilot.", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    argv = argv if argv is not None else sys.argv[1:]
    path = pathlib.Path(argv[0] if argv else ROOT / "docs" / "engagement" / "roi-inputs.demo.yaml")
    cfg = load(path)
    rows = [json.loads(line) for line in (ROOT / cfg["replay"]).read_text().splitlines()]
    r = compute(cfg, rows)
    out = ROOT / "docs" / "engagement" / path.name.replace("roi-inputs.", "roi-").replace(".yaml", ".md")
    out.write_text(sheet(cfg, r))
    print(f"wrote {out.relative_to(ROOT)}; net a month low/mid/high: " + ", ".join(f"R{r['cases'][c]['net_zar']}" for c in CASES))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""The owner-facing analyses, run on the demo tenant in CI so they cannot rot.

    python -m frontdesk_ml.analyses --out reports/analyses   (also rewrites docs/evidence/insights-demo.md)

Inputs are all committed and synthetic: the demo replay (`docs/evidence/replay-demo-offline/
replay.jsonl`), the labelled evaluation questions, twelve weeks of hourly volume, and the
experiment pre-registrations. No database, no model, no network. Each section states its
method, the number, and what the number cannot tell you.
"""

from __future__ import annotations

import argparse
import json
import pathlib
from collections import Counter

import numpy as np

from frontdesk import drift
from frontdesk.stats import fmt_rate

from . import ab, clustering, dataset, forecast

ROOT = pathlib.Path(__file__).resolve().parents[2]
REPLAY = ROOT / "docs" / "evidence" / "replay-demo-offline" / "replay.jsonl"
EVIDENCE = ROOT / "docs" / "evidence" / "insights-demo.md"
PREREG = ROOT / "experiments" / "exp-2026-11-lead-with-answer.yaml"


def _naive_psi(base: Counter, cur: Counter, eps: float = 1e-4) -> float:
    """The first version: every intent kept, empty ones floored at a tiny epsilon."""
    nb, nc = sum(base.values()) or 1, sum(cur.values()) or 1
    out = 0.0
    for c in set(base) | set(cur):
        b, a = max(base.get(c, 0) / nb, eps), max(cur.get(c, 0) / nc, eps)
        out += (a - b) * np.log(a / b)
    return out


def _with_share(p: np.ndarray, i: int, share: float) -> np.ndarray:
    q = p * (1 - share) / (1 - p[i])
    q[i] = share
    return q


def alarm_rates(mix: Counter, sizes=(30, 50, 100, 300), sims: int = 1000, seed: int = 11) -> list[dict]:
    """For each weekly volume: how often each rule says "shifted" when nothing changed (false
    alarms), and how often the rule used catches a load-shedding week in which fault reports go
    from under 1% of messages to 8% (moderate) or 15% (severe). Baseline: four weeks at the same volume."""
    rng = np.random.default_rng(seed)
    cats = sorted(mix)
    p = np.asarray([mix[c] for c in cats], dtype=float)
    p /= p.sum()
    moderate, severe = _with_share(p, cats.index("fault"), 0.08), _with_share(p, cats.index("fault"), 0.15)
    rows = []
    for n in sizes:
        naive_fa = rule_fa = hit_mod = hit_sev = 0
        for _ in range(sims):
            base = Counter(dict(zip(cats, rng.multinomial(4 * n, p))))
            same = Counter(dict(zip(cats, rng.multinomial(n, p))))
            naive_fa += _naive_psi(base, same) >= drift.SHIFTED
            rule_fa += drift.score(base, same)["level"] == "shifted"
            hit_mod += drift.score(base, Counter(dict(zip(cats, rng.multinomial(n, moderate)))))["level"] == "shifted"
            hit_sev += drift.score(base, Counter(dict(zip(cats, rng.multinomial(n, severe)))))["level"] == "shifted"
        rows.append({"messages_per_week": n, "naive_false_alarms": naive_fa / sims, "rule_false_alarms": rule_fa / sims,
                     "rule_detects_faults_at_8_percent": hit_mod / sims, "rule_detects_faults_at_15_percent": hit_sev / sims})
    return rows


def run(out: pathlib.Path, evidence: pathlib.Path = EVIDENCE) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    replay = [json.loads(line) for line in REPLAY.read_text().splitlines()]
    results: dict = {}
    md = ["# Owner insights on the demo tenant (synthetic data)", "",
          "Generated by `python -m frontdesk_ml.analyses`; runs in CI on every pull request. Every input is",
          "made up (Bushveld Solar & Electrical does not exist), so these numbers show the method, not a market.", ""]

    # 1. Rates with confidence intervals
    n = len(replay)
    answered = sum(r["action"] == "answer" for r in replay)
    after = [r for r in replay if r["after_hours"]]
    after_answered = sum(r["action"] == "answer" for r in after)
    results["rates"] = {"answered": [answered, n], "after_hours_answered": [after_answered, len(after)]}
    md += ["## 1. Rates, with their uncertainty", "",
           f"- Answered from the documents: {fmt_rate(answered, n)}",
           f"- Of the messages that arrived after hours, answered at once: {fmt_rate(after_answered, len(after))}", "",
           "Intervals are Wilson 95%. With a month of messages from one business, a 6-point-wide interval is",
           "the honest precision; a single percentage would claim more than the data holds.", ""]

    # 2. Topics in what could not be answered
    gaps = [r["question_redacted"] for r in replay if r["handoff_reason"] == "unanswerable"]
    topics, noise = clustering.topics(gaps)
    items = dataset.load() + dataset.load(dataset.HOLDOUT)
    quality = clustering.evaluate([i.text for i in items], [i.intent for i in items])
    results["topics"] = [{"size": t.size, "keywords": t.keywords, "example": t.example} for t in topics]
    results["clustering_quality"] = quality
    md += ["## 2. What the documents are missing, grouped into topics", "",
           f"{len(gaps)} replayed questions were handed over because no document answered them. UMAP (to 5",
           "dimensions) then HDBSCAN groups them; each topic is named by class-based TF-IDF and shown with",
           "its most central question.", "",
           "| Topic (top words) | Questions | Most central example |", "|---|---|---|"]
    md += [f"| {', '.join(t.keywords)} | {t.size} | {t.example} |" for t in topics]
    md += [f"| (not in any topic) | {len(noise)} | {noise[0] if noise else ''} |", "",
           f"How good is the grouping? On the {quality['n']} labelled evaluation questions ({quality['intents']} intents):",
           "", "| Method | Questions clustered | Adjusted Rand index | NMI |", "|---|---|---|---|",
           f"| UMAP + HDBSCAN (used) | {1 - quality['noise_share']:.0%} | {quality['umap_hdbscan_ari']} | {quality['umap_hdbscan_nmi']} |",
           f"| HDBSCAN without UMAP | {1 - quality['hdbscan_without_umap_noise_share']:.0%} | {quality['hdbscan_without_umap_ari']} | |",
           f"| k-means, told the true number of intents | 100% | {quality['kmeans_ari']} | {quality['kmeans_nmi']} |", "",
           "Without UMAP, HDBSCAN gives up on about half the questions (calls them noise) and scores only the",
           "easy half. The embeddings here are character n-grams, so topics follow wording; Cohere multilingual",
           "embeddings on the Bedrock pipeline group by meaning (a seam until the dev account exists).", ""]

    # 3. Volume forecast
    weeks = forecast.load_weeks()
    bt = forecast.backtest(weeks)
    nxt = forecast.next_week(weeks)
    results["forecast"] = {"backtest": bt, "next_week": nxt}
    md += ["## 3. When messages will arrive next week", "",
           f"Twelve weeks of hourly counts; rolling-origin backtest over the last four weeks.", "",
           "| Method | MAE per hour | MASE (below 1 beats last week) | Weekly total error | 80% interval coverage | coverage, busy hours |",
           "|---|---|---|---|---|---|"]
    md += [f"| {k} | {v['mae_per_hour']} | {v['mase']} | {v['weekly_total_error']:.0%} | {v['coverage_80']:.0%} | {v['coverage_80_busy_hours']:.0%} |"
           for k, v in bt.items()]
    md += ["", f"Next week ({nxt['method']}): about **{nxt['total']} messages** (80% range {nxt['total_80'][0]} to "
           f"{nxt['total_80'][1]}); **{nxt['closed_share']:.0%} arrive while the office is closed**. Busiest hours: "
           f"{', '.join(nxt['busiest'])}.", "",
           "Limits: the intervals over-cover (they are conservative) because hourly counts are small whole",
           "numbers; load-shedding evenings are not predictable from the calendar and show up as misses.", ""]

    # 4. Drift: an alarm rule that works at tens of messages a week
    mix = Counter(r["intent"] for r in replay)
    mix.setdefault("fault", 1)
    rates = alarm_rates(mix)
    results["drift"] = rates
    md += ["## 4. Drift in what customers ask about", "",
           "The weekly job compares this week's intent mix with the four weeks before. Simulated with the demo",
           "mix: how often each rule calls a week \"shifted\" when nothing changed, and how often the rule used",
           "catches a load-shedding week in which fault reports rise from under 1% of messages to 8% or 15%.", "",
           "| Messages this week | First version (PSI >= 0.25): false alarms | Rule used: false alarms | Rule used: catches faults at 8% | at 15% |",
           "|---|---|---|---|---|"]
    md += [f"| {r['messages_per_week']} | {r['naive_false_alarms']:.0%} | {r['rule_false_alarms']:.1%} | "
           f"{r['rule_detects_faults_at_8_percent']:.0%} | {r['rule_detects_faults_at_15_percent']:.0%} |" for r in rates]
    md += ["", "The first version (every intent kept, empty ones floored at a tiny epsilon) alarmed on noise most",
           "weeks at small-business volume, so it was replaced before it shipped. The rule used merges intents",
           "under 5% into \"other\", smooths counts, and needs PSI >= 0.25 *and* a chi-square p < 0.01",
           "(`backend/frontdesk/drift.py`): about one false alarm a year when run weekly. Below about 50",
           "messages a week it misses many real shifts; that is the price of not crying wolf, and the insights",
           "screen still shows the raw intent counts. At 300 messages the 8% case sits on the 0.25 line, so about",
           "half of those weeks are reported as \"watch\" rather than \"shifted\": the effect-size threshold working.", ""]

    # 5. A/B testing at SME scale
    pr = ab.load_prereg(PREREG)
    per_week = answered / 30 * 7
    peek = ab.simulate_peeking()
    results["ab"] = {"per_week_answered": round(per_week, 1), "n_per_arm": pr.n_per_arm, "peeking": peek}
    md += ["## 5. Can one small business A/B test a prompt?", "",
           f"The pre-registered experiment `{pr.data['id']}` needs {pr.n_per_arm} customers per arm to see 80% -> 85%.",
           f"At the demo tenant's {per_week:.0f} answered customers a week:", "", "```", ab.plan_text(pr, per_week), "```", "",
           f"And why the tool refuses to look early: in {peek['sims']} simulated A/A tests (no real difference), a fixed",
           f"horizon declared a false winner {peek['false_positive_fixed_horizon']:.1%} of the time; checking {peek['looks']} times",
           f"and stopping at the first p < 0.05 did so {peek['false_positive_with_peeking']:.1%} of the time.", "",
           "Conclusion for a pilot: test prompts offline on the evaluation set and the replay first; run a live A/B",
           "only for large expected effects, or across several consenting clients.", ""]

    text = "\n".join(md) + "\n"
    evidence.write_text(text)
    (out / "analyses.json").write_text(json.dumps(results, indent=2, default=str))
    return results


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="reports/analyses")
    a = ap.parse_args(argv)
    r = run(pathlib.Path(a.out))
    print(f"analyses written: {EVIDENCE.relative_to(ROOT)}; {len(r['topics'])} topics; "
          f"forecast MASE {r['forecast']['backtest']['level x profile']['mase']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
